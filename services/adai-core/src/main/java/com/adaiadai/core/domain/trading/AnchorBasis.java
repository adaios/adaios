package com.adaiadai.core.domain.trading;

/**
 * AnchorBasis — 券商快照**基准日的依据**（2026-10-05，P2-交易84）。
 *
 * <p><b>为什么要有这个类型</b>：锚定日原先只有「值」没有「据」——盘前导入时靠
 * {@code LocalDate.now()/LocalTime.now()} + 09:30 阈值猜「数据基准日」。猜对了没人知道，
 * 猜错了（如 09:26 导出、09:28 导入被退到上一交易日）也没人知道，且锚定日只前进不后退，
 * 错了就再也退不回来。现在把「这一天是怎么定下来的」变成**随锚定一起落盘的事实**，
 * 对账回执（{@code GET /trading/integrity}）与导入回执都据它如实说话（有据 / 无据）。
 *
 * <p>与 {@code SnapshotAnchor#positionsFileDate()} 的分工：文件日期只说「用户在文件名里写了哪天」，
 * 本枚举说「最终锚定日是**根据什么**定下来的」——两者合起来才能区分「确定的采用」与「时钟的猜测」。
 *
 * <p><b>老落盘文件没有这个字段</b>（null）＝ 不可判定：既有语义保持不变（由文件日期与锚定日是否
 * 相等推断，见 {@link SnapshotAnchor#positionsDateInferred()}），**不诬告**。
 */
public enum AnchorBasis {

    /**
     * **有据**：导入方（用户/前端）显式给出了数据基准日（{@code basedOn=YYYY-MM-DD}）。
     * <p>它优先于时钟推断——这正是 P2-交易84 的修法：09:26 导出、09:28 导入不再因为
     * 「导入时刻 &lt; 09:30」被退到上一交易日。
     */
    EXPLICIT,

    /** **有据**：直接采用文件里的日期（补导历史快照，未发生归一化——文件本身就是证据）。 */
    FILE_DATE,

    /**
     * **有据**：文件日期当天休市（周末/法定节假日）→ 数据基准日 = 上一交易日是**确定的**
     * （由交易日历可自证，不是猜的）。沿用 2026-10-03（b90f56a2）确立的口径：这类归一化静默。
     */
    CLOSED_DAY,

    /**
     * **无据**：时钟推断兜底（文件日期是交易日却被退到上一交易日、或压根没有文件日期）。
     * <p>这是最后的兜底：不猜就没法防重，但**必须如实标「无据」**，让对账闸门能把
     * 「锚定日当天的成交可能并不在快照里」摆到台面上（P1-交易61 / P2-交易62 的旁路）。
     */
    CLOCK;

    /** 是否为「有据」的依据（时钟推断以外的都算有据）。 */
    public boolean withEvidence() {
        return this != CLOCK;
    }

    /** 回执人话（导入回执 / 对账 note 直显；不出现系统视角标签，只说事实）。 */
    public String label() {
        return switch (this) {
            case EXPLICIT -> "按你指定的数据基准日";
            case FILE_DATE -> "按快照文件里的日期";
            case CLOSED_DAY -> "文件日期当天休市，基准日取上一交易日";
            case CLOCK -> "按导入时间推断";
        };
    }
}
